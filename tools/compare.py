"""Offline comparison of scenario sources (groundwork for the Phase 3 evaluation).

For each example request that has readings and an intended behaviour, a scripted person answers
from the intended behaviour under each strategy, with a budget of one, two and three questions:

- deviation:  a scenario in which at least one reading acts against the intended behaviour;
- shared:     a deviation that every reading shares, so no divergence question can raise it;
- exposed:    a deviation in a scenario that was asked. Exposure is necessary, not sufficient,
              for a person to notice a deviation; this script has no person in it.
- correct:    one reading is left and it matches the intended behaviour in every scenario.

  py -3.11 tools/compare.py                       recorded readings (data/recorded_readings.json)
  py -3.11 tools/compare.py --fixed               Lab 3's hand-written readings (requests A and B)
  py -3.11 tools/compare.py --out docs/comparison.md

The intended behaviours were written by the student, so this is a pilot of the method, not evidence
about published tasks (planned for Phase 3).
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from checker import readings, scripted, simulator  # noqa: E402

STRATEGIES = ["divergence", "boundary", "combined", "random"]
BUDGETS = [1, 2, 3]
SEEDS = 20


def load(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def deviations(cands, scenarios, intended):
    rows = {}
    for s in scenarios:
        wrong = [r["id"] for r in cands if simulator.simulate(r, s) != intended[s["id"]]]
        if wrong:
            rows[s["id"]] = {"wrong": wrong, "shared": len(wrong) == len(cands)}
    return rows


def correct(run, scenarios, intended):
    left = run["remaining"]
    return len(left) == 1 and all(simulator.simulate(left[0], s) == intended[s["id"]] for s in scenarios)


def evaluate(cands, scenarios, intended):
    devs = deviations(cands, scenarios, intended)
    out = {}
    for strategy in STRATEGIES:
        for budget in BUDGETS:
            seeds = range(SEEDS) if strategy == "random" else [0]
            totals = {"exposed": 0.0, "shared_exposed": 0.0, "correct": 0.0, "asked": 0.0}
            runs = []
            for seed in seeds:
                run = scripted.run(cands, scenarios, intended, strategy, budget, seed)
                runs.append(run)
                exposed = [sid for sid in run["asked"] if sid in devs]
                totals["exposed"] += len(exposed)
                totals["shared_exposed"] += sum(1 for sid in exposed if devs[sid]["shared"])
                totals["correct"] += correct(run, scenarios, intended)
                totals["asked"] += len(run["asked"])
            n = len(seeds)
            out[(strategy, budget)] = {k: v / n for k, v in totals.items()} | {
                "example_run": runs[0], "example_correct": correct(runs[0], scenarios, intended)}
    return devs, out


def fmt(x):
    return f"{x:.0f}" if abs(x - round(x)) < 1e-9 else f"{x:.1f}"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fixed", action="store_true", help="use Lab 3's hand-written readings")
    parser.add_argument("--out", help="write the report to this Markdown file")
    args = parser.parse_args()
    scenarios = load("data/scenarios.json")["scenarios"]
    lines = []
    say = lines.append
    source = "Lab 3 hand-written readings (simulated)" if args.fixed else "recorded Gemini readings"
    say(f"# Offline comparison of scenario sources ({source})")
    say("")
    say("Generated by `tools/compare.py`. A pilot of the Phase 3 method: the intended behaviours were written by the "
        "student, and exposure is necessary, not sufficient, for a person to notice a deviation.")
    say("")
    cases = []
    for spec in load("data/requests.json")["requests"]:
        if "intended" not in spec:
            continue
        generated = readings.generate(spec["text"], "fixed" if args.fixed else "recorded")
        if generated.error or generated.unsupported or not generated.readings:
            continue
        cands = simulator.distinct(generated.readings, scenarios)[0]
        devs, results = evaluate(cands, scenarios, spec["intended"])
        cases.append((spec, generated, cands, devs, results))
    if not cases:
        say("No request has both readings and an intended behaviour.")
    else:
        say("## Requests and deviations")
        say("")
        say("| Request | Readings | Deviations (scenario: readings that deviate) | Shared by all readings |")
        say("|---|---|---|---|")
        for spec, generated, cands, devs, _ in cases:
            listed = "; ".join(f"{sid}: {', '.join(d['wrong'])}" for sid, d in devs.items()) or "none"
            shared = ", ".join(sid for sid, d in devs.items() if d["shared"]) or "none"
            model = generated.source.get("model", generated.source.get("kind"))
            say(f"| {spec['id']} ({spec['about']}) | {len(cands)} ({model}) | {listed} | {shared} |")
        say("")
        total = sum(len(c[3]) for c in cases)
        shared_total = sum(1 for c in cases for d in c[3].values() if d["shared"])
        say(f"## Totals over {len(cases)} requests ({total} deviations, {shared_total} shared)")
        say("")
        say("Random is the mean of 20 seeds. Cells: deviations exposed / shared deviations exposed / correct saved "
            "rules / questions asked.")
        say("")
        say("| Strategy | 1 question | 2 questions | 3 questions |")
        say("|---|---|---|---|")
        for strategy in STRATEGIES:
            cells = []
            for budget in BUDGETS:
                agg = {k: sum(c[4][(strategy, budget)][k] for c in cases)
                       for k in ("exposed", "shared_exposed", "correct", "asked")}
                cells.append(f"{fmt(agg['exposed'])}/{total} · {fmt(agg['shared_exposed'])}/{shared_total} · "
                             f"{fmt(agg['correct'])}/{len(cases)} · {fmt(agg['asked'])}")
            say(f"| {strategy} | " + " | ".join(cells) + " |")
        say("")
        say("## Questions asked with a budget of three (random: seed 0)")
        say("")
        say("| Request | " + " | ".join(STRATEGIES) + " |")
        say("|---|" + "---|" * len(STRATEGIES))
        for spec, _, _, devs, results in cases:
            cells = []
            for strategy in STRATEGIES:
                result = results[(strategy, 3)]
                run = result["example_run"]
                asked = ", ".join(f"{sid}{'*' if sid in devs else ''}" for sid in run["asked"]) or "none"
                left = len(run["remaining"])
                end = ("saved rule correct" if result["example_correct"] else "saved rule wrong") if left == 1 \
                    else f"{left} rules left"
                cells.append(f"{asked} ({end})")
            say(f"| {spec['id']} | " + " | ".join(cells) + " |")
        say("")
        say("`*` marks a question that exposed a deviation.")
    text = "\n".join(lines) + "\n"
    if args.out:
        (ROOT / args.out).write_text(text, encoding="utf-8")
        print(f"Wrote {args.out}")
    print(text)


if __name__ == "__main__":
    main()
